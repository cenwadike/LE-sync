//! I/O glue only: parse args, collect, execute the guest, judge the journal (Sprints 4 and 5: also
//! prints the verified account/slot values and the verified log), then, with `--prove`, prove the
//! same run and save the receipt, or, with `--verify-receipt`, check a saved receipt. Every
//! decision with logic in it lives in `le_sync` (lib.rs) where it is unit-tested. This file needs
//! the built guest ELF to run, so it is excluded from mutation testing (see
//! `.cargo/mutants.toml`).

use le_sync::{
    collect_checked, expected_binding, judge, judge_receipt_journal, parse_args, proof_run_error,
    split_proof_args, usage_error_text, verdict_exit_code, Opts, Verdict,
};
use le_sync_core::sync::ChainBinding;
use le_sync_wire::{check_chain_binding, GuestInput, GuestOutput};
use risc0_zkvm::{default_executor, default_prover, ExecutorEnv, Receipt};
use std::{env, fs, path::Path, process::ExitCode};

// Generated by build.rs: GUEST_ELF (bundled ProgramBinary) and GUEST_ID.
include!(concat!(env!("OUT_DIR"), "/methods.rs"));

fn build_env(input: &GuestInput) -> Result<ExecutorEnv<'static>, String> {
    ExecutorEnv::builder()
        .write(input)
        .and_then(|b| b.build())
        .map_err(|e| format!("building the executor env: {e}"))
}

/// Receipts made with `RISC0_DEV_MODE` carry no proof. Refuse to produce or accept one.
fn dev_mode_set() -> bool {
    env::var_os("RISC0_DEV_MODE").is_some()
}

fn main() -> ExitCode {
    env_logger::init();
    let (proof, rest) = match split_proof_args(env::args().skip(1)) {
        Ok(p) => p,
        Err(e) => {
            eprint!("{}", usage_error_text(&e));
            return ExitCode::from(2);
        }
    };
    let opts = match parse_args(rest) {
        Ok(o) => o,
        Err(e) => {
            eprint!("{}", usage_error_text(&e));
            return ExitCode::from(2);
        }
    };
    if proof.prove || proof.verify_receipt.is_some() {
        if let Some(why) = proof_run_error(&opts) {
            eprint!("{}", usage_error_text(why));
            return ExitCode::from(2);
        }
        if dev_mode_set() {
            eprintln!("RISC0_DEV_MODE is set: its receipts are fake. Unset it to prove or verify.");
            return ExitCode::FAILURE;
        }
    }
    if let Some(path) = &proof.verify_receipt {
        return verify_saved_receipt(&opts, path);
    }

    // 1. host does all I/O. `expected` is the chain binding built from the host's OWN
    //    configuration (never from what --other-chain / --cross-config alter).
    let collected = match collect_checked(&opts) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };

    // 2. guest does all verification (execute first: fast, gives cycles and the journal)
    let env = match build_env(&collected.input) {
        Ok(e) => e,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("executing guest (id {:?})...", GUEST_ID);
    let info = match default_executor().execute(env, GUEST_ELF) {
        Ok(i) => i,
        Err(e) => {
            eprintln!("guest execution failed: {e}");
            return ExitCode::FAILURE;
        }
    };

    // 3. trust only what the guest committed
    let out: GuestOutput = match info.journal.decode() {
        Ok(o) => o,
        Err(e) => {
            eprintln!("journal decode failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("cycles: {}", info.cycles());
    println!("journal: {out:?}");

    let verdict = report(&opts, &out, collected.expected.as_ref());
    if verdict != Verdict::Ok || !proof.prove {
        return ExitCode::from(verdict_exit_code(&verdict));
    }

    // 4. only after every check passed: prove the same run
    let path = proof
        .receipt_out
        .as_deref()
        .expect("--prove needs --receipt-out (enforced by split_proof_args)");
    prove_and_save(&collected.input, &info.journal.bytes, path)
}

/// Prove the run, verify the receipt against this build's image ID, require its journal to be
/// the executed one, and only then write it.
fn prove_and_save(input: &GuestInput, executed_journal: &[u8], path: &Path) -> ExitCode {
    let env = match build_env(input) {
        Ok(e) => e,
        Err(e) => {
            eprintln!("error: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("proving (this takes a while)...");
    let started = std::time::Instant::now();
    let prove_info = match default_prover().prove(env, GUEST_ELF) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("proving failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("proved in {:.1?}", started.elapsed());
    let receipt = prove_info.receipt;
    if let Err(e) = receipt.verify(GUEST_ID) {
        eprintln!("the receipt does not verify against this build's guest image ID: {e}");
        return ExitCode::FAILURE;
    }
    let verdict = judge_receipt_journal(executed_journal, &receipt.journal.bytes);
    if verdict != Verdict::Ok {
        eprintln!("NOT OK: the receipt's journal differs from the journal the guest executed to");
        return ExitCode::from(verdict_exit_code(&verdict));
    }
    let bytes = match bincode::serialize(&receipt) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("serializing the receipt failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    if let Err(e) = fs::write(path, &bytes) {
        eprintln!("writing {}: {e}", path.display());
        return ExitCode::FAILURE;
    }
    println!(
        "receipt verified and saved: {} ({} bytes)",
        path.display(),
        bytes.len()
    );
    ExitCode::SUCCESS
}

/// `--verify-receipt`: no guest run. The receipt must verify against this build's image ID,
/// then its journal is judged exactly like a live one. The chain binding comes from `--source`
/// (a saved directory works offline), never from the receipt.
fn verify_saved_receipt(opts: &Opts, path: &Path) -> ExitCode {
    let bytes = match fs::read(path) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("reading {}: {e}", path.display());
            return ExitCode::FAILURE;
        }
    };
    let receipt: Receipt = match bincode::deserialize(&bytes) {
        Ok(r) => r,
        Err(e) => {
            eprintln!("{} is not a receipt: {e}", path.display());
            return ExitCode::FAILURE;
        }
    };
    if let Err(e) = receipt.verify(GUEST_ID) {
        eprintln!("the receipt does not verify against this build's guest image ID: {e}");
        return ExitCode::FAILURE;
    }
    println!("receipt verified against guest id {:?}", GUEST_ID);
    let out: GuestOutput = match receipt.journal.decode() {
        Ok(o) => o,
        Err(e) => {
            eprintln!("journal decode failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("journal: {out:?}");
    let expected = if opts.wants_sync() {
        match expected_binding(opts) {
            Ok(b) => Some(b),
            Err(e) => {
                eprintln!("error: {e}");
                return ExitCode::FAILURE;
            }
        }
    } else {
        None
    };
    let verdict = report(opts, &out, expected.as_ref());
    ExitCode::from(verdict_exit_code(&verdict))
}

/// Judge the journal and print the result. Shared by a live run and `--verify-receipt`, so both
/// are held to the same checks. Returns the verdict.
fn report(opts: &Opts, out: &GuestOutput, expected: Option<&ChainBinding>) -> Verdict {
    // The chain check is the first judgement made on the journal (see `judge`). The journal
    // printed by the caller is diagnostics only; nothing in it is trusted before that check.
    let verdict = judge(opts, out, expected);
    match &verdict {
        Verdict::Ok => {
            if let Some(exp) = expected.filter(|_| opts.expects_chain_mismatch()) {
                if let Err(e) = check_chain_binding(out, exp) {
                    println!(
                        "chain mismatch detected, as expected for this run (code {}): {}",
                        e.code(),
                        e.message()
                    );
                }
            }
            if opts.state.requested() && !(opts.state.tamper_state || opts.state.tamper_exec) {
                println!(
                    "state (verified in the guest under finalized slot {}): block {} hash 0x{} state_root 0x{}",
                    out.finalized_slot,
                    out.exec_block_number,
                    hex::encode(out.exec_block_hash),
                    hex::encode(out.exec_state_root)
                );
                println!(
                    "  account 0x{} present={} balance 0x{}",
                    hex::encode(out.state_address),
                    out.account_present,
                    hex::encode(out.account_balance)
                );
                println!(
                    "  slot 0x{} value 0x{}",
                    hex::encode(out.state_slot),
                    hex::encode(out.state_value)
                );
                if let Some(p) = &out.state_predicate {
                    println!("  predicate held: {p:?}");
                }
                println!(
                    "  statement ids: account 0x{} slot 0x{}",
                    hex::encode(out.account_statement_id),
                    hex::encode(out.state_statement_id)
                );
            } else if opts.state.requested() {
                println!(
                    "state rejected by the guest, as expected for this run (code {})",
                    out.state_error_code
                );
            }
            if opts.state.log.requested()
                && !(opts.state.tamper_exec || opts.state.log.tamper_receipt)
            {
                println!(
                    "log (verified in the guest under finalized slot {}): block {} hash 0x{} receipts_root 0x{}",
                    out.finalized_slot,
                    out.log_block_number,
                    hex::encode(out.log_block_hash),
                    hex::encode(out.log_receipts_root)
                );
                println!(
                    "  transaction {} log {} emitted by 0x{}",
                    out.log_tx_index,
                    out.log_index,
                    hex::encode(out.log_address)
                );
                for i in 0..out.log_topic_count as usize {
                    println!("  topic{i} 0x{}", hex::encode(out.log_topics[i]));
                }
                println!(
                    "  data {} bytes, keccak256 0x{}",
                    out.log_data_len,
                    hex::encode(out.log_data_hash)
                );
                if let Some(p) = &out.log_predicate {
                    println!("  predicate held: {p:?}");
                }
                println!(
                    "  statement id 0x{}",
                    hex::encode(out.log_statement_id)
                );
            } else if opts.state.log.requested() {
                println!(
                    "log rejected by the guest, as expected for this run (code {})",
                    out.log_error_code
                );
            }
            println!("OK");
        }
        Verdict::ChainMismatch(e) => {
            eprintln!("CHAIN MISMATCH (code {}): {}", e.code(), e.message());
            if let Some(exp) = expected {
                eprintln!(
                    "  expected: chain_id {} genesis_validators_root 0x{}",
                    exp.chain_id,
                    hex::encode(exp.genesis_validators_root)
                );
            }
            eprintln!(
                "  journal:  chain_id {} genesis_validators_root 0x{}",
                out.chain_id,
                hex::encode(out.genesis_validators_root)
            );
        }
        Verdict::ChainMismatchNotDetected => eprintln!(
            "NOT OK: this run presented another chain, but the journal commits the host's own chain"
        ),
        Verdict::TrustedRootDiffers => {
            eprintln!("journal trusted_root differs from the requested one")
        }
        Verdict::StateNotOk => eprintln!(
            "NOT OK: the committed state section is not what was asked for (state_checked={}, state_ok={}, error code {})",
            out.state_checked, out.state_ok, out.state_error_code
        ),
        Verdict::LogNotOk => eprintln!(
            "NOT OK: the committed log section is not what was asked for (log_checked={}, log_ok={}, error code {})",
            out.log_checked, out.log_ok, out.log_error_code
        ),
        Verdict::ReceiptJournalDiffers => {
            eprintln!("NOT OK: the receipt's journal differs from the executed journal")
        }
        Verdict::NotOk => eprintln!("NOT OK"),
    }
    verdict
}
