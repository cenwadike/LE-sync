//! Sprint 6 M1 cost gate: the three staged update steps, execute-only.
//!
//! For one scenario (`fixture`): run Begin, Miller and Finish natively (`run_stage` with the
//! blst backend), then each step in the RISC Zero executor on `../guest-stage`, feeding the
//! guest's own output forward. Every guest result must equal the native result for the same
//! input, byte for byte, including the error code of a rejected step. Nothing is proved.
//!
//! Output: a table (see `report`), and one machine line for `scripts/env.sh` (`le_cost`):
//!   cost: scenario=<name> begin=<n> miller=<n> finish=<n>      (executor cycles)
//!
//! `--input lez` runs `guest-stage/src/lez_stage.rs` instead: the same steps with the inputs
//! written, and the result committed, the way a LEZ program's are (accounts, instruction words,
//! the whole `ProgramOutput`; see `lez_io.rs`). That is the number to compare with the cap.
//! `--keys N` measures decoding N committee keys (`guest-stage/src/keys.rs`) and nothing else.
//!
//! Exit: 0 all steps match and (if `--cap`) none is over it; 1 otherwise; 2 bad arguments.

mod fixture;
// Shared with the guest, so both sides agree on the layout by construction.
#[path = "../../guest-stage/src/lez_io.rs"]
mod lez_io;
mod report;

use le_sync_wire::bls::Impl;
use le_sync_wire::stage::{run_stage, StageConfig, StageInput, StageOutput};
use report::{GuestLine, Row};
use risc0_zkvm::{default_executor, ExecutorEnv};
use std::io::Write;
use std::process::ExitCode;
use std::sync::{Arc, Mutex};

// Generated by build.rs: GUEST_STAGE_{ELF,ID}, LEZ_STAGE_{ELF,ID} and KEYS_{ELF,ID}.
include!(concat!(env!("OUT_DIR"), "/methods.rs"));

type StepResult = Result<StageOutput, u16>;

/// A cloneable writer, so the bytes the guest logs can be read after the executor owns a copy.
#[derive(Clone, Default)]
struct Sink(Arc<Mutex<Vec<u8>>>);

impl Write for Sink {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

struct Guest {
    result: StepResult,
    executor_cycles: u64,
    line: GuestLine,
    log: String,
}

fn native(cfg: &StageConfig, input: &StageInput) -> StepResult {
    run_stage(cfg, input, &Impl).map_err(|e| e.code())
}

fn env_err<E: std::fmt::Display>(e: E) -> String {
    format!("building the executor env: {e}")
}

/// The accounts and instruction words a LEZ program receives for `input`.
/// Begin [store, empty job slot]; Miller [job]; Finish [store, job].
fn lez_inputs(
    cfg: &StageConfig,
    input: &StageInput,
) -> Result<(Vec<lez_io::AccountWithMetadata>, Vec<u32>), String> {
    let (accounts, op) = match input {
        StageInput::Begin { store, update } => (
            vec![lez_io::meta(1, store.clone()), lez_io::meta(2, vec![])],
            lez_io::LezOp::Begin {
                update: update.clone(),
            },
        ),
        StageInput::Miller { job } => (vec![lez_io::meta(2, job.clone())], lez_io::LezOp::Miller),
        StageInput::Finish { job, store, update } => (
            vec![lez_io::meta(1, store.clone()), lez_io::meta(2, job.clone())],
            lez_io::LezOp::Finish {
                update: update.clone(),
            },
        ),
    };
    let words = risc0_zkvm::serde::to_vec(&(cfg, &op))
        .map_err(|e| format!("serializing the instruction: {e}"))?;
    Ok((accounts, words))
}

/// The step result a committed `ProgramOutput` carries: the job in the last post state
/// (Begin, Miller) or the new store in the first (Finish).
fn lez_result(input: &StageInput, out: Result<lez_io::ProgramOutput, u16>) -> StepResult {
    let out = out?;
    let data = |i: usize| out.post_states[i].account.data.as_slice().to_vec();
    Ok(match input {
        StageInput::Begin { .. } => StageOutput::Job(data(1)),
        StageInput::Miller { .. } => StageOutput::Job(data(0)),
        StageInput::Finish { .. } => StageOutput::Store(data(0)),
    })
}

fn run_guest(cfg: &StageConfig, input: &StageInput, lez: bool) -> Result<Guest, String> {
    let sink = Sink::default();
    let mut builder = ExecutorEnv::builder();
    builder.stdout(sink.clone());
    if lez {
        let (accounts, words) = lez_inputs(cfg, input)?;
        let program_id: lez_io::ProgramId = [1; 8];
        // the order `Program::write_inputs` uses
        builder.write(&program_id).map_err(env_err)?;
        builder.write(&None::<lez_io::ProgramId>).map_err(env_err)?;
        builder.write(&accounts).map_err(env_err)?;
        builder.write(&words).map_err(env_err)?;
    } else {
        builder.write(&(cfg, input)).map_err(env_err)?;
    }
    let env = builder
        .build()
        .map_err(|e| format!("building the executor env: {e}"))?;
    let elf = if lez { LEZ_STAGE_ELF } else { GUEST_STAGE_ELF };
    let info = default_executor()
        .execute(env, elf)
        .map_err(|e| format!("guest execution failed: {e}"))?;
    let result: StepResult = if lez {
        let out: Result<lez_io::ProgramOutput, u16> = info
            .journal
            .decode()
            .map_err(|e| format!("journal decode failed: {e}"))?;
        lez_result(input, out)
    } else {
        info.journal
            .decode()
            .map_err(|e| format!("journal decode failed: {e}"))?
    };
    let log = String::from_utf8_lossy(&sink.0.lock().unwrap()).into_owned();
    let line = report::parse_guest_line(&log)
        .ok_or_else(|| format!("no `guest-stage cycles:` line in the guest log:\n{log}"))?;
    Ok(Guest {
        result,
        executor_cycles: info.cycles(),
        line,
        log,
    })
}

/// `--keys N`: decode N committee keys in the guest, compressed and hinted, and print the cost.
fn run_keys(n: usize) -> ExitCode {
    let keys: Vec<Vec<u8>> = le_sync_testkit::committee(1, n)
        .pubkeys
        .iter()
        .map(|k| k.to_vec())
        .collect();
    let sink = Sink::default();
    let mut builder = ExecutorEnv::builder();
    builder.stdout(sink.clone());
    let env = match builder.write(&keys).and_then(|b| b.build()) {
        Ok(e) => e,
        Err(e) => {
            eprintln!("building the executor env: {e}");
            return ExitCode::FAILURE;
        }
    };
    if let Err(e) = default_executor().execute(env, KEYS_ELF) {
        eprintln!("keys guest failed: {e}");
        return ExitCode::FAILURE;
    }
    let log = String::from_utf8_lossy(&sink.0.lock().unwrap()).into_owned();
    let Some(line) = report::parse_keys_line(&log) else {
        eprintln!("no `keys cycles:` line in the guest log:\n{log}");
        return ExitCode::FAILURE;
    };
    print!("{}", report::keys_table(&line));
    ExitCode::SUCCESS
}

fn input_bytes(i: &StageInput) -> usize {
    match i {
        StageInput::Begin { store, update } => store.len() + fixture::update_bytes(update),
        StageInput::Miller { job } => job.len(),
        StageInput::Finish { job, store, update } => {
            job.len() + store.len() + fixture::update_bytes(update)
        }
    }
}

fn output_bytes(r: &StepResult) -> usize {
    match r {
        Ok(StageOutput::Job(b)) | Ok(StageOutput::Store(b)) => b.len(),
        Err(_) => 0,
    }
}

fn describe(r: &StepResult) -> String {
    match r {
        Ok(StageOutput::Job(b)) => format!("job ({} bytes)", b.len()),
        Ok(StageOutput::Store(b)) => format!("store ({} bytes)", b.len()),
        Err(code) => format!("error code {code}"),
    }
}

fn main() -> ExitCode {
    let opts = match report::parse_args(std::env::args().skip(1)) {
        Ok(o) => o,
        Err(e) => {
            eprintln!("error: {e}\n\n{}", report::USAGE);
            return ExitCode::from(2);
        }
    };
    if opts.help {
        print!("{}", report::USAGE);
        return ExitCode::SUCCESS;
    }

    if let Some(n) = opts.keys {
        return run_keys(n);
    }

    let lez = opts.input == "lez";
    println!(
        "building the {} fixture: {} members, real signatures...",
        opts.scenario, opts.committee
    );
    let w = match fixture::build(opts.committee, &opts.scenario) {
        Ok(w) => w,
        Err(e) => {
            eprintln!("fixture: {e}");
            return ExitCode::FAILURE;
        }
    };
    println!(
        "scenario {}: {} of {} members sign; store {} bytes",
        opts.scenario,
        w.present,
        w.total,
        w.store.len()
    );
    if lez {
        println!("input format: lez (accounts + instruction words in, whole ProgramOutput out)");
        println!("guest image id {:?}", LEZ_STAGE_ID);
    } else {
        println!("input format: plain (store and update read directly, only the result committed)");
        println!("guest image id {:?}", GUEST_STAGE_ID);
    }

    let mut rows: Vec<Row> = vec![];
    let mut ok = true;
    let mut job: Vec<u8> = vec![];
    for step in ["begin", "miller", "finish"] {
        let input = match step {
            "begin" => StageInput::Begin {
                store: w.store.clone(),
                update: w.update.clone(),
            },
            "miller" => StageInput::Miller { job: job.clone() },
            _ => StageInput::Finish {
                job: job.clone(),
                store: w.store.clone(),
                update: w.update.clone(),
            },
        };
        let want = native(&w.cfg, &input);
        if let Err(code) = &want {
            // the fixture itself is wrong (or the update is not valid): nothing to compare
            eprintln!("{step}: the native reference run rejects this input (error code {code}); stopping before the guest");
            return ExitCode::FAILURE;
        }
        let got = match run_guest(&w.cfg, &input, lez) {
            Ok(g) => g,
            Err(e) => {
                eprintln!("{step}: {e}");
                return ExitCode::FAILURE;
            }
        };
        if got.result != want {
            eprintln!(
                "{step}: MISMATCH: guest gave {}, native gave {}",
                describe(&got.result),
                describe(&want)
            );
            ok = false;
        }
        if got.line.mode != step {
            eprintln!("{step}: the guest reports mode {}", got.line.mode);
            ok = false;
        }
        if opts.detail {
            println!("--- {step}: guest log");
            for l in got.log.lines() {
                println!("    {l}");
            }
        }
        rows.push(Row {
            step,
            input_bytes: input_bytes(&input),
            output_bytes: output_bytes(&got.result),
            guest: got.line,
            executor: got.executor_cycles,
        });
        match got.result {
            Ok(StageOutput::Job(j)) => job = j,
            Ok(StageOutput::Store(_)) => {}
            Err(_) => break,
        }
        if !ok {
            break;
        }
    }

    println!();
    print!("{}", report::table(&rows, opts.cap));
    if rows.len() != 3 || !ok {
        println!("\nbench: FAIL (guest and native differ, or a step stopped early)");
        return ExitCode::FAILURE;
    }
    if report::over_cap(&rows, opts.cap) {
        println!("\nbench: FAIL (a step is over the cap)");
        return ExitCode::FAILURE;
    }
    println!("\nbench: all three guest results equal the native results");
    if let Some(line) = report::cost_line(&opts.scenario, &rows) {
        println!("{line}");
    }
    ExitCode::SUCCESS
}
